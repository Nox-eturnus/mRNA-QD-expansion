    axes[0].set_ylabel('hit rate at 1000 shots')
    axes[0].set_ylim(-0.02, 1.05)
    fig.legend(loc='lower center', ncol=4, bbox_to_anchor=(0.5, -0.1), fontsize=8)
    fig.suptitle('Hit rate vs problem size', x=0.01, ha='left', fontsize=10, color=INK)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, 'fig5_scaling.png'))
