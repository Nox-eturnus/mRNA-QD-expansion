def jl(name):
    p = os.path.join(RES, name)
    return [json.loads(l) for l in open(p) if l.strip()] if os.path.exists(p) else []


def boot(vals, n=2000, seed=0):
    rng = random.Random(seed)
    k = len(vals)
    if k == 0:
        return float('nan'), float('nan')
    m = sorted(sum(rng.choice(vals) for _ in range(k)) / k for _ in range(n))
    return m[int(0.025 * n)], m[int(0.975 * n)]


def fmt_ci(vals):
    lo, hi = boot(vals)
    return f'{mean(vals):.3f} [{lo:.3f}, {hi:.3f}]'


def fmt_d(a, b):
    d = [x - y for x, y in zip(a, b)]
    lo, hi = boot(d)
    return f'{mean(d):+.3f} [{lo:+.3f}, {hi:+.3f}]'


class Tables:
    def __init__(self):
        self.parts = []

    def h(self, title):
        self.parts.append(f'\n## {title}\n')

    def p(self, text):
        self.parts.append(text + '\n')

    def table(self, header, rows):
        self.parts.append('| ' + ' | '.join(header) + ' |')
        self.parts.append('|' + '|'.join('---' for _ in header) + '|')
        for r in rows:
            self.parts.append('| ' + ' | '.join(str(x) for x in r) + ' |')
        self.parts.append('')

    def write(self, path):
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write('# Tables (generated by scripts/make_report.py; do not edit)\n')
            f.write('\n'.join(self.parts) + '\n')


