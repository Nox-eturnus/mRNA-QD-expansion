"""Evaluation tables and figures.

Recomputes every reported number from the committed result
files, writes the tables to report/tables.md and the figures to
report/figures/*.png.  Nothing is re-run; this only reads results.

    python scripts/make_report.py

Tiers follow the baseline (WISER-Moderna evaluate.py):
  Tier 1   energy: optimality of the exact solver, energy gap of quantum samples
  Tier 2a  QUBO optimum vs the ViennaRNA MFE structure (model fidelity)
  Tier 2b  structure vs the experimental (FR3D) reference: sensitivity, PPV, MCC
Every mean is over chains; 95 % intervals are percentile bootstraps over
chains (2000 resamples, seed 0); paired differences are bootstrapped per chain.
"""

